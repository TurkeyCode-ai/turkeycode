/**
 * A throwaway local copy of the built app for simulated visitors to act on.
 *
 * Visitors submit forms, so this is never the copy a person is using. It runs
 * under its own Compose project name, on its own port, with its own database
 * volumes, and `stop()` destroys all of it. The project's `.env` is not loaded,
 * so the copy holds no real keys and cannot send mail or take payments with
 * them.
 */

import { execFileSync, spawnSync } from 'child_process';
import { mkdirSync, writeFileSync } from 'fs';
import { createServer } from 'net';
import { join } from 'path';
import { detectProject, type ProjectDetection } from '../deploy/detect';
import { resolveAppPort } from '../deploy/droplet';
import { buildCompose, composeToYaml, resolveMigrateCmd, type ComposeFile, type ComposeService } from '../deploy/run-local';

export interface LocalApp {
  url: string;
  /** Throw the data away and start again from empty. */
  reset(): Promise<void>;
  /** Stop the copy and delete its containers and volumes. */
  stop(): void;
}

export interface SimComposeOptions {
  hostPort: number;
  appPort: number;
  /** Extra environment for the app, from --env. Wins over generated values. */
  env?: Record<string, string>;
}

/**
 * The run-local services, changed for a simulation: only the app is published,
 * on a loopback port of its own, so nothing collides with a running
 * `turkeycode run-local` and nothing is reachable from another machine.
 */
export function simCompose(compose: ComposeFile, options: SimComposeOptions): ComposeFile {
  const services: Record<string, ComposeService> = {};
  for (const [name, original] of Object.entries(compose.services)) {
    const svc: ComposeService = { ...original, restart: 'no' };
    delete svc.ports;
    if (name === 'app') {
      svc.ports = [`127.0.0.1:${options.hostPort}:${options.appPort}`];
      svc.environment = { ...(original.environment ?? {}), PORT: String(options.appPort), ...(options.env ?? {}) };
    }
    services[name] = svc;
  }
  return { version: '', services, volumes: compose.volumes };
}

/** The Compose project name for the copy. Distinct from run-local's. */
export function simProjectName(appName: string): string {
  const base = appName.toLowerCase().replace(/[^a-z0-9-]/g, '-').replace(/^-+|-+$/g, '') || 'app';
  return `${base.slice(0, 40)}-sim`;
}

export function dockerComposeAvailable(): boolean {
  try {
    execFileSync('docker', ['compose', 'version'], { stdio: 'ignore', timeout: 15_000 });
    execFileSync('docker', ['info'], { stdio: 'ignore', timeout: 15_000 });
    return true;
  } catch {
    return false;
  }
}

function freePort(): Promise<number> {
  return new Promise((resolve, reject) => {
    const server = createServer();
    server.unref();
    server.on('error', reject);
    server.listen(0, '127.0.0.1', () => {
      const address = server.address();
      const port = typeof address === 'object' && address ? address.port : 0;
      server.close(() => resolve(port));
    });
  });
}

/** Any HTTP answer below 500 means the app is up. */
async function waitForHttp(url: string, timeoutMs: number): Promise<boolean> {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    try {
      const res = await fetch(url, { redirect: 'manual', signal: AbortSignal.timeout(5_000) });
      if (res.status < 500) return true;
    } catch { /* not listening yet */ }
    await new Promise(r => setTimeout(r, 1_000));
  }
  return false;
}

export interface StartLocalAppOptions {
  /** A folder outside the project for the generated Compose file. */
  home: string;
  env?: Record<string, string>;
  log?: (line: string) => void;
  /** Injected in tests. */
  detection?: ProjectDetection;
}

/** Builds and starts the copy. Throws with the reason if it will not start. */
export async function startLocalApp(cwd: string, options: StartLocalAppOptions): Promise<LocalApp> {
  const log = options.log ?? (() => {});
  const detection = options.detection ?? detectProject(cwd);
  const appPort = resolveAppPort(detection, cwd);
  const hostPort = await freePort();
  const project = simProjectName(detection.name);

  // buildCompose also writes Dockerfile.turkeycode when the project has none.
  const compose = simCompose(buildCompose(detection, cwd, { loadDotEnv: false }), { hostPort, appPort, env: options.env });
  mkdirSync(options.home, { recursive: true });
  const composePath = join(options.home, 'compose.yml');
  writeFileSync(composePath, composeToYaml(compose, '# Generated by turkeycode simulate. A throwaway copy.\n\n'));

  const dependencies = Object.keys(compose.services).filter(s => s !== 'app');
  const migrateCmd = resolveMigrateCmd(detection, cwd);
  const url = `http://127.0.0.1:${hostPort}`;

  // stdin is closed on every call: a compose command that reads it would hang.
  const dc = (args: string[], quiet = false): number => {
    const result = spawnSync(
      'docker',
      ['compose', '-f', composePath, '--project-directory', cwd, '-p', project, ...args],
      { stdio: ['ignore', quiet ? 'ignore' : 'inherit', quiet ? 'ignore' : 'inherit'] }
    );
    return result.status ?? 1;
  };

  const down = () => { dc(['down', '--volumes', '--remove-orphans'], true); };

  const up = async (): Promise<void> => {
    if (dependencies.length > 0 && dc(['up', '-d', '--quiet-pull', '--wait', ...dependencies], true) !== 0) {
      // Not every image has a health check; give the rest a moment.
      await new Promise(r => setTimeout(r, 8_000));
    }
    if (migrateCmd && dc(['run', '--rm', '-T', 'app', 'sh', '-c', migrateCmd], true) !== 0) {
      log('  The migration command failed on the copy; carrying on.');
    }
    if (dc(['up', '-d', '--quiet-pull'], true) !== 0) throw new Error('The copy of the app did not start.');
    if (!(await waitForHttp(url, 120_000))) {
      throw new Error(`The copy of the app started but did not answer on ${url} within 2 minutes.`);
    }
  };

  down(); // a copy left over from an interrupted simulation
  log('  Building a throwaway copy of the app...');
  if (dc(['build'], true) !== 0) {
    down();
    throw new Error('The app image did not build. Run `turkeycode run-local` to see the build output.');
  }
  try {
    await up();
  } catch (err) {
    down();
    throw err;
  }

  return {
    url,
    async reset() {
      down();
      await up();
    },
    stop: down,
  };
}
